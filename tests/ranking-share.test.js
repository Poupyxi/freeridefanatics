const {calendarDate,calendarEvents,calendarLinks,calendarFile}=require('../assets/js/ranking-share.js');
assert.equal(calendarDate('2027-02-29'),null);
assert.equal(calendarDate('2028-02-29'),'2028-02-29');
assert.equal(calendarDate('9999-01-01'),null);
assert.equal(calendarDate('TBA'),null);
const events=calendarEvents([{name:'Les Gets, France; épreuve\nfinale',date:'2027-12-31',location:'France'},{name:'Weekend',date:'2028-02-28',endDate:'2028-02-29'},{name:'Unknown',date:'9999-01-01'}],'UCI 2027','https://preprod.ridersfanatics.com/competitions/uci.html');
assert.equal(events.length,2);assert.equal(events[0].end,'2028-01-01');assert.equal(events[1].end,'2028-03-01');
assert.equal(new URL(calendarLinks(events[0]).google).searchParams.get('dates'),'20271231/20280101');
assert.equal(new URL(calendarLinks(events[0]).outlook).searchParams.get('allday'),'true');
const file=calendarFile(events,new Date('2026-11-07T19:00:00Z'));
assert.equal((file.match(/BEGIN:VEVENT/g)||[]).length,2);
assert(file.includes('DTEND;VALUE=DATE:20280101\r\n'));
assert(file.includes('SUMMARY:Les Gets\\, France\\; épreuve\\nfinale'));
assert(file.includes('DTSTAMP:20261107T190000Z'));
assert(file.endsWith('END:VCALENDAR\r\n'));
assert(file.split('\r\n').every(line=>Buffer.byteLength(line)<=75));
const unicode=calendarFile([{...events[0],title:'Événement 🚲 '.repeat(30)}]);
assert(unicode.split('\r\n').every(line=>Buffer.byteLength(line)<=75));
assert(unicode.replace(/\r\n /g,'').includes('SUMMARY:'+'Événement 🚲 '.repeat(30)));
assert(calendarFile([{...events[0],cancelled:true}]).includes('STATUS:CANCELLED'));
